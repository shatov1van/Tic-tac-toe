# Исключения в Python — это события, которые возникают во время выполнения программы 
# и сигнализируют о том, что что-то пошло не так, как ожидалось.
# Чтобы описать собственное исключение, нужно создать новый класс, 
# который наследуется от встроенного класса Exception или его подклассов.

# Пример «укрощения» исключения:
