# Класс ошибки, если вышли за границы поля
class FieldIndexError(IndexError):
    """Выбрасывается, если выбрано значение вне поля."""

    def __init__(self, msg='Введено значение за границами игрового поля!'):
        super().__init__(msg)

# Класс ошибки, если ячейка уже занята
class CellOccupiedError(Exception):
    def __init__(self, msg='Дорогой друг, ячейка занята. Пожалуйста, введи другие координаты…'):
        super().__init__(msg)